"""Builds lot-plan-data.js from the Trucker Heaven parking lot diagram PDF.

Usage: python3 tools/build_lot_plan.py "TH PARKING LOT DIAGRAME.pdf"
Requires PyMuPDF (pip install pymupdf). Every numbered space is traced from the diagram's own
linework: the rectangle around each number is bounded by the nearest painted lines.
"""
import collections, json, sys
import pymupdf

page = pymupdf.open(sys.argv[1])[0]
H, V, rects, pills, marks = [], [], [], [], []
for group in page.get_drawings():
    items = group["items"]
    if any(item[0] == "c" for item in items):
        r = group["rect"]
        entry = [round(r.x0, 1), round(r.y0, 1), round(r.x1 - r.x0, 1), round(r.y1 - r.y0, 1)]
        (marks if group.get("fill") else pills).append(entry)
        continue
    for item in items:
        if item[0] == "l":
            a, b = item[1], item[2]
            if abs(a.y - b.y) < 0.6: H.append((round((a.y + b.y) / 2, 1), min(a.x, b.x), max(a.x, b.x)))
            elif abs(a.x - b.x) < 0.6: V.append((round((a.x + b.x) / 2, 1), min(a.y, b.y), max(a.y, b.y)))
        elif item[0] == "re":
            r = item[1]
            fill = group.get("fill")
            rects.append({"x": round(r.x0, 1), "y": round(r.y0, 1), "w": round(r.x1 - r.x0, 1), "h": round(r.y1 - r.y0, 1),
                          "filled": bool(fill), "light": bool(fill) and fill[0] > 0.5})

def merge(segments):
    by = collections.defaultdict(list)
    for c, a, b in segments: by[c].append([a, b])
    out = []
    for c, spans in by.items():
        spans.sort(); cur = spans[0][:]
        for a, b in spans[1:]:
            if a <= cur[1] + 1.5: cur[1] = max(cur[1], b)
            else: out.append((c, cur[0], cur[1])); cur = [a, b]
        out.append((c, cur[0], cur[1]))
    return out

H, V = merge(H), merge(V)
spots = {}
for x0w, y0w, x1w, y1w, text, *_ in page.get_text("words"):
    if not text.isdigit(): continue
    cx, cy = (x0w + x1w) / 2, (y0w + y1w) / 2
    above = [h for h in H if h[1] - 1 <= cx <= h[2] + 1 and h[0] < cy]
    below = [h for h in H if h[1] - 1 <= cx <= h[2] + 1 and h[0] > cy]
    left = [v for v in V if v[1] - 1 <= cy <= v[2] + 1 and v[0] < cx]
    right = [v for v in V if v[1] - 1 <= cy <= v[2] + 1 and v[0] > cx]
    top = max(above, key=lambda h: h[0]) if above else None
    bot = min(below, key=lambda h: h[0]) if below else None
    lf = max(left, key=lambda v: v[0]) if left else None
    rt = min(right, key=lambda v: v[0]) if right else None
    dy = bot[0] - top[0] if top and bot else (32 if bot and bot[0] - cy < 40 else 1e9)
    dx = rt[0] - lf[0] if lf and rt else 1e9
    if dy <= dx or dy < 45:  # a long stall lying across the row
        y0 = top[0] if top else bot[0] - 31.9
        y1 = bot[0] if bot else top[0] + 31.9
        segs = [s for s in (top, bot) if s]
        x0, x1 = max(s[1] for s in segs), min(s[2] for s in segs)
        if lf and x0 < lf[0] < cx: x0 = lf[0]
        if rt and cx < rt[0] < x1: x1 = rt[0]
    else:  # a stall standing upright, side by side with its neighbours
        x0, x1 = lf[0], rt[0]
        y0, y1 = max(lf[1], rt[1]), min(lf[2], rt[2])
        if top and y0 < top[0] < cy: y0 = top[0]
        if bot and cy < bot[0] < y1: y1 = bot[0]
    spots[text] = [round(x0, 1), round(y0, 1), round(x1 - x0, 1), round(y1 - y0, 1)]

labels = []
for block in page.get_text("dict")["blocks"]:
    for line in block.get("lines", []):
        text = "".join(span["text"] for span in line["spans"]).strip()
        if text and not text.isdigit():
            x0, y0, x1, y1 = line["bbox"]
            labels.append({"text": text, "x": round((x0 + x1) / 2, 1), "y": round((y0 + y1) / 2, 1), "vertical": line["dir"][1] != 0})

data = {
    "source": "TH PARKING LOT DIAGRAME - Copy 5.pdf",
    "viewBox": [150, 10, 1430, 2575],
    "spots": spots,
    "lines": [[c, round(a, 1), round(b, 1), "h"] for c, a, b in H] + [[c, round(a, 1), round(b, 1), "v"] for c, a, b in V],
    "buildings": [r for r in rects if r["w"] > 150 and r["h"] > 60],
    "structures": [r for r in rects if not (r["w"] > 150 and r["h"] > 60)],
    "pills": pills,
    "marks": marks,
    "labels": labels,
}
assert len(spots) == 185, len(spots)
with open("lot-plan-data.js", "w") as out:
    out.write("/* Generated by tools/build_lot_plan.py from the Trucker Heaven lot diagram. Do not edit by hand. */\n")
    out.write("(function (root) { const data = ")
    out.write(json.dumps(data, separators=(",", ":")))
    out.write("; if (typeof module === 'object' && module.exports) module.exports = data; else root.LotPlanData = data; })(typeof self !== 'undefined' ? self : this);\n")
print(f"{len(spots)} spaces, {len(data['lines'])} lines, {len(data['buildings'])} buildings")
