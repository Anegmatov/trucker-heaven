-- Phase 7C: immutable operational pickup and return inspection evidence.
CREATE TABLE rental_inspections (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reservation_id INTEGER NOT NULL REFERENCES reservationsmvp (reservationid) ON DELETE RESTRICT,
  vehicle_id INTEGER NOT NULL REFERENCES vehicles (vehicleid) ON DELETE RESTRICT,
  inspection_type VARCHAR(10) NOT NULL CHECK (inspection_type IN ('PICKUP', 'RETURN')),
  odometer INTEGER NOT NULL CHECK (odometer >= 0),
  fuel_level_percent SMALLINT NOT NULL CHECK (fuel_level_percent BETWEEN 0 AND 100),
  damage_observed BOOLEAN NOT NULL,
  damage_notes VARCHAR(1000),
  cleanliness_notes VARCHAR(1000),
  keys_count SMALLINT NOT NULL CHECK (keys_count BETWEEN 0 AND 20),
  all_expected_keys_returned BOOLEAN,
  accessories_returned BOOLEAN,
  accessories_notes VARCHAR(1000),
  completed_by_admin_user_id INTEGER NOT NULL REFERENCES admin_users (id) ON DELETE RESTRICT,
  completed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT rental_inspections_reservation_type_unique UNIQUE (reservation_id, inspection_type),
  CONSTRAINT rental_inspections_damage_notes_check CHECK (
    (damage_observed AND damage_notes IS NOT NULL AND length(damage_notes) > 0) OR
    (NOT damage_observed AND damage_notes IS NULL)
  ),
  CONSTRAINT rental_inspections_return_fields_check CHECK (
    (inspection_type = 'RETURN' AND all_expected_keys_returned IS NOT NULL AND accessories_returned IS NOT NULL) OR
    (inspection_type = 'PICKUP' AND all_expected_keys_returned IS NULL AND accessories_returned IS NULL)
  )
);

CREATE INDEX idx_rental_inspections_reservation ON rental_inspections (reservation_id, inspection_type);
CREATE INDEX idx_rental_inspections_vehicle ON rental_inspections (vehicle_id, completed_at DESC);
CREATE INDEX idx_rental_inspections_completed_at ON rental_inspections (completed_at DESC);

CREATE FUNCTION prevent_rental_inspection_mutation() RETURNS trigger AS $$
BEGIN
  RAISE EXCEPTION 'completed rental inspections are immutable';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER rental_inspections_immutable
  BEFORE UPDATE OR DELETE ON rental_inspections
  FOR EACH ROW EXECUTE FUNCTION prevent_rental_inspection_mutation();
