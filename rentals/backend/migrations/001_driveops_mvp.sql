-- DriveOps MVP PostgreSQL schema. Applied by `npm run migrate`.
-- Runtime code manages updatedat whenever a mutable row changes.

CREATE TABLE IF NOT EXISTS vehicles (
  vehicleid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vin VARCHAR(40) UNIQUE,
  platenumber VARCHAR(40) UNIQUE,
  make VARCHAR(80) NOT NULL,
  model VARCHAR(80) NOT NULL,
  year INTEGER NOT NULL CHECK (year BETWEEN 1886 AND 9999),
  color VARCHAR(40),
  category VARCHAR(40) NOT NULL,
  seats INTEGER NOT NULL DEFAULT 5 CHECK (seats > 0),
  transmission VARCHAR(40) NOT NULL DEFAULT 'Automatic',
  fueltype VARCHAR(40) NOT NULL DEFAULT 'Gasoline',
  mileage INTEGER NOT NULL DEFAULT 0 CHECK (mileage >= 0),
  dailyrate NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (dailyrate >= 0),
  depositamount NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (depositamount >= 0),
  locationname VARCHAR(120) NOT NULL DEFAULT 'Trucker Heaven Rentals - Mt. Juliet',
  status VARCHAR(30) NOT NULL DEFAULT 'Available',
  notes TEXT,
  createdat TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedat TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_vehicles_status ON vehicles (status);
CREATE INDEX IF NOT EXISTS idx_vehicles_category ON vehicles (category);
CREATE INDEX IF NOT EXISTS idx_vehicles_location ON vehicles (locationname);

CREATE TABLE IF NOT EXISTS vehiclephotos (
  photoid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vehicleid INTEGER NOT NULL REFERENCES vehicles (vehicleid) ON DELETE CASCADE,
  imageurl VARCHAR(1024) NOT NULL,
  storagekey VARCHAR(512),
  phototype VARCHAR(40) NOT NULL DEFAULT 'PUBLIC',
  isprimary BOOLEAN NOT NULL DEFAULT FALSE,
  sortorder INTEGER NOT NULL DEFAULT 0 CHECK (sortorder >= 0),
  createdat TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_vehiclephotos_vehicle ON vehiclephotos (vehicleid);
CREATE INDEX IF NOT EXISTS idx_vehiclephotos_primary ON vehiclephotos (vehicleid, isprimary);
CREATE UNIQUE INDEX IF NOT EXISTS uq_vehiclephotos_primary_per_vehicle
  ON vehiclephotos (vehicleid) WHERE isprimary;

CREATE TABLE IF NOT EXISTS reservationsmvp (
  reservationid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vehicleid INTEGER NOT NULL REFERENCES vehicles (vehicleid) ON DELETE RESTRICT,
  customername VARCHAR(160),
  customeremail VARCHAR(160),
  customerphone VARCHAR(40),
  pickupat TIMESTAMPTZ NOT NULL,
  returnat TIMESTAMPTZ NOT NULL,
  status VARCHAR(30) NOT NULL DEFAULT 'PENDING_REQUEST',
  estimatedtotal NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (estimatedtotal >= 0),
  depositamount NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (depositamount >= 0),
  smsstatus VARCHAR(40),
  smslog TEXT,
  createdat TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedat TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (returnat > pickupat)
);

CREATE INDEX IF NOT EXISTS idx_reservationsmvp_vehicle ON reservationsmvp (vehicleid);
CREATE INDEX IF NOT EXISTS idx_reservationsmvp_status ON reservationsmvp (status);
CREATE INDEX IF NOT EXISTS idx_reservationsmvp_overlap
  ON reservationsmvp (vehicleid, pickupat, returnat)
  WHERE UPPER(status) IN ('CONFIRMED', 'CHECKED_OUT');
