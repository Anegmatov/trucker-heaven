UPDATE admin_users SET role = 'STAFF' WHERE role = 'MANAGER';
ALTER TABLE admin_users DROP CONSTRAINT IF EXISTS admin_users_role_check;
ALTER TABLE admin_users ADD CONSTRAINT admin_users_role_check CHECK (role IN ('OWNER', 'STAFF'));

CREATE TABLE food_categories (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  description VARCHAR(500),
  display_order INTEGER NOT NULL DEFAULT 0 CHECK (display_order >= 0),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX uq_food_categories_name_lower ON food_categories (LOWER(name));
CREATE INDEX idx_food_categories_public ON food_categories (is_active, display_order, id);

CREATE TABLE food_items (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id INTEGER NOT NULL REFERENCES food_categories (id) ON DELETE RESTRICT,
  name VARCHAR(140) NOT NULL,
  description VARCHAR(1000),
  price_cents INTEGER NOT NULL CHECK (price_cents >= 0 AND price_cents <= 1000000),
  image_url VARCHAR(1024),
  display_order INTEGER NOT NULL DEFAULT 0 CHECK (display_order >= 0),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  is_sold_out BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_food_items_public ON food_items (category_id, is_active, display_order, id);

CREATE TABLE food_orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_number VARCHAR(32) NOT NULL UNIQUE,
  customer_name VARCHAR(160) NOT NULL,
  customer_phone VARCHAR(40) NOT NULL,
  pickup_type VARCHAR(12) NOT NULL CHECK (pickup_type IN ('ASAP', 'SCHEDULED')),
  pickup_at TIMESTAMPTZ,
  customer_notes VARCHAR(1000),
  status VARCHAR(20) NOT NULL DEFAULT 'NEW' CHECK (status IN ('NEW', 'ACCEPTED', 'PREPARING', 'READY', 'COMPLETED', 'REJECTED', 'CANCELLED')),
  payment_method VARCHAR(20) NOT NULL DEFAULT 'PAY_AT_PICKUP' CHECK (payment_method = 'PAY_AT_PICKUP'),
  payment_status VARCHAR(12) NOT NULL DEFAULT 'UNPAID' CHECK (payment_status IN ('UNPAID', 'PAID')),
  subtotal_cents INTEGER NOT NULL CHECK (subtotal_cents >= 0),
  total_cents INTEGER NOT NULL CHECK (total_cents >= 0),
  client_request_key VARCHAR(100),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK ((pickup_type = 'ASAP' AND pickup_at IS NULL) OR (pickup_type = 'SCHEDULED' AND pickup_at IS NOT NULL))
);
CREATE UNIQUE INDEX uq_food_orders_client_request_key ON food_orders (client_request_key) WHERE client_request_key IS NOT NULL;
CREATE INDEX idx_food_orders_queue ON food_orders (status, created_at DESC);

CREATE TABLE food_order_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  food_order_id BIGINT NOT NULL REFERENCES food_orders (id) ON DELETE RESTRICT,
  food_item_id INTEGER REFERENCES food_items (id) ON DELETE SET NULL,
  item_name VARCHAR(140) NOT NULL,
  unit_price_cents INTEGER NOT NULL CHECK (unit_price_cents >= 0),
  quantity INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 99),
  line_total_cents INTEGER NOT NULL CHECK (line_total_cents >= 0)
);
CREATE INDEX idx_food_order_items_order ON food_order_items (food_order_id, id);

CREATE TABLE food_order_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  food_order_id BIGINT NOT NULL REFERENCES food_orders (id) ON DELETE RESTRICT,
  admin_user_id INTEGER REFERENCES admin_users (id) ON DELETE SET NULL,
  event_type VARCHAR(30) NOT NULL CHECK (event_type IN ('STATUS_CHANGED', 'PAYMENT_CHANGED')),
  previous_value VARCHAR(20),
  next_value VARCHAR(20) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_food_order_history_order ON food_order_history (food_order_id, created_at DESC);
