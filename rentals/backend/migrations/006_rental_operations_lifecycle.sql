-- Phase 7A: forward-only operational reservation lifecycle.
-- Existing rows retain their status and do not receive fabricated history.
DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM reservationsmvp
    WHERE UPPER(status) NOT IN ('PENDING_REQUEST', 'CONFIRMED', 'READY_FOR_PICKUP', 'CHECKED_OUT',
      'RETURNED_PENDING_INSPECTION', 'COMPLETED', 'DECLINED', 'CANCELLED', 'NO_SHOW')
  ) THEN
    RAISE EXCEPTION 'Cannot migrate reservation statuses: unsupported status values exist';
  END IF;
  IF EXISTS (
    SELECT 1 FROM reservationsmvp earlier
    JOIN reservationsmvp later ON later.vehicleid = earlier.vehicleid
      AND later.reservationid > earlier.reservationid
      AND tstzrange(earlier.pickupat, earlier.returnat, '[)') && tstzrange(later.pickupat, later.returnat, '[)')
    WHERE UPPER(earlier.status) IN ('CONFIRMED', 'READY_FOR_PICKUP', 'CHECKED_OUT', 'RETURNED_PENDING_INSPECTION')
      AND UPPER(later.status) IN ('CONFIRMED', 'READY_FOR_PICKUP', 'CHECKED_OUT', 'RETURNED_PENDING_INSPECTION')
  ) THEN
    RAISE EXCEPTION 'Cannot add Phase 7A overlap protection: existing blocking reservations overlap';
  END IF;
END $$;

ALTER TABLE reservationsmvp
  DROP CONSTRAINT IF EXISTS reservationsmvp_status_transition_values_check,
  ADD CONSTRAINT reservationsmvp_status_transition_values_check
    CHECK (UPPER(status) IN ('PENDING_REQUEST', 'CONFIRMED', 'READY_FOR_PICKUP', 'CHECKED_OUT',
      'RETURNED_PENDING_INSPECTION', 'COMPLETED', 'DECLINED', 'CANCELLED', 'NO_SHOW')),
  ADD COLUMN statusversion INTEGER NOT NULL DEFAULT 1,
  ADD CONSTRAINT reservationsmvp_statusversion_check CHECK (statusversion > 0);

ALTER TABLE reservationsmvp DROP CONSTRAINT IF EXISTS reservationsmvp_blocking_interval_exclusion;
DROP INDEX IF EXISTS idx_reservationsmvp_blocking_interval;
ALTER TABLE reservationsmvp
  ADD CONSTRAINT reservationsmvp_blocking_interval_exclusion
  EXCLUDE USING gist (
    vehicleid WITH =,
    tstzrange(pickupat, returnat, '[)') WITH &&
  ) WHERE (UPPER(status) IN ('CONFIRMED', 'READY_FOR_PICKUP', 'CHECKED_OUT', 'RETURNED_PENDING_INSPECTION'));
CREATE INDEX idx_reservationsmvp_blocking_interval
  ON reservationsmvp USING gist (vehicleid, tstzrange(pickupat, returnat, '[)'))
  WHERE UPPER(status) IN ('CONFIRMED', 'READY_FOR_PICKUP', 'CHECKED_OUT', 'RETURNED_PENDING_INSPECTION');

CREATE TABLE reservation_status_history (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reservation_id INTEGER NOT NULL REFERENCES reservationsmvp (reservationid) ON DELETE RESTRICT,
  from_status VARCHAR(40) NOT NULL CHECK (from_status IN ('PENDING_REQUEST', 'CONFIRMED', 'READY_FOR_PICKUP', 'CHECKED_OUT', 'RETURNED_PENDING_INSPECTION', 'COMPLETED', 'DECLINED', 'CANCELLED', 'NO_SHOW')),
  to_status VARCHAR(40) NOT NULL CHECK (to_status IN ('PENDING_REQUEST', 'CONFIRMED', 'READY_FOR_PICKUP', 'CHECKED_OUT', 'RETURNED_PENDING_INSPECTION', 'COMPLETED', 'DECLINED', 'CANCELLED', 'NO_SHOW')),
  status_version INTEGER NOT NULL CHECK (status_version > 0),
  actor_admin_user_id INTEGER REFERENCES admin_users (id) ON DELETE SET NULL,
  operation VARCHAR(40) NOT NULL CHECK (operation IN ('CONFIRM', 'DECLINE', 'CANCEL', 'READY_FOR_PICKUP', 'CHECK_OUT', 'MARK_RETURNED', 'COMPLETE', 'NO_SHOW')),
  reason VARCHAR(500),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (from_status <> to_status)
);
CREATE UNIQUE INDEX uq_reservation_status_history_reservation_version ON reservation_status_history (reservation_id, status_version);
CREATE INDEX idx_reservation_status_history_reservation_created ON reservation_status_history (reservation_id, created_at, id);

CREATE FUNCTION prevent_reservation_status_history_mutation() RETURNS trigger AS $$
BEGIN
  RAISE EXCEPTION 'reservation status history is append-only';
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER reservation_status_history_immutable
  BEFORE UPDATE OR DELETE ON reservation_status_history
  FOR EACH ROW EXECUTE FUNCTION prevent_reservation_status_history_mutation();
