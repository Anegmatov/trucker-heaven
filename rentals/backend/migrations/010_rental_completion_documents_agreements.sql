-- Phase 9: secure, incomplete-by-default rental completion records.
ALTER TABLE reservationsmvp ADD COLUMN IF NOT EXISTS customer_access_token_hash CHAR(64);
CREATE UNIQUE INDEX IF NOT EXISTS uq_reservations_customer_access_token_hash ON reservationsmvp (customer_access_token_hash) WHERE customer_access_token_hash IS NOT NULL;

CREATE TABLE rental_documents (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reservation_id INTEGER NOT NULL REFERENCES reservationsmvp(reservationid) ON DELETE RESTRICT,
  document_type VARCHAR(20) NOT NULL CHECK (document_type IN ('DRIVER_LICENSE','INSURANCE')),
  storage_name VARCHAR(80) NOT NULL UNIQUE,
  mime_type VARCHAR(40) NOT NULL CHECK (mime_type IN ('image/jpeg','image/png','image/webp','application/pdf')),
  byte_size INTEGER NOT NULL CHECK (byte_size > 0),
  review_status VARCHAR(20) NOT NULL DEFAULT 'NOT_SUBMITTED' CHECK (review_status IN ('NOT_SUBMITTED','PENDING_REVIEW','APPROVED','REJECTED')),
  review_note VARCHAR(1000), reviewed_by_admin_user_id INTEGER REFERENCES admin_users(id) ON DELETE SET NULL, reviewed_at TIMESTAMPTZ,
  uploaded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT rental_documents_review_consistency CHECK ((review_status IN ('APPROVED','REJECTED') AND reviewed_at IS NOT NULL) OR (review_status IN ('NOT_SUBMITTED','PENDING_REVIEW')))
);
CREATE INDEX idx_rental_documents_reservation ON rental_documents(reservation_id, document_type, uploaded_at DESC);

CREATE TABLE rental_agreements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reservation_id INTEGER NOT NULL REFERENCES reservationsmvp(reservationid) ON DELETE RESTRICT,
  revision INTEGER NOT NULL CHECK (revision > 0), agreement_version VARCHAR(40) NOT NULL,
  terms_snapshot TEXT NOT NULL, reservation_snapshot JSONB NOT NULL,
  customer_signer_name VARCHAR(160), customer_signed_at TIMESTAMPTZ,
  staff_signer_name VARCHAR(160), staff_signed_at TIMESTAMPTZ, staff_admin_user_id INTEGER REFERENCES admin_users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_rental_agreements_revision UNIQUE(reservation_id, revision),
  CONSTRAINT rental_agreements_customer_signature CHECK ((customer_signer_name IS NULL AND customer_signed_at IS NULL) OR (customer_signer_name IS NOT NULL AND customer_signed_at IS NOT NULL)),
  CONSTRAINT rental_agreements_staff_signature CHECK ((staff_signer_name IS NULL AND staff_signed_at IS NULL AND staff_admin_user_id IS NULL) OR (staff_signer_name IS NOT NULL AND staff_signed_at IS NOT NULL AND staff_admin_user_id IS NOT NULL))
);

CREATE TABLE rental_internal_notes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reservation_id INTEGER NOT NULL REFERENCES reservationsmvp(reservationid) ON DELETE RESTRICT,
  admin_user_id INTEGER REFERENCES admin_users(id) ON DELETE SET NULL,
  note_type VARCHAR(30) NOT NULL CHECK (note_type IN ('OPERATIONAL','MANUAL_PAYMENT','MANUAL_DEPOSIT')),
  note VARCHAR(1000) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_rental_internal_notes_reservation ON rental_internal_notes(reservation_id, created_at DESC);
