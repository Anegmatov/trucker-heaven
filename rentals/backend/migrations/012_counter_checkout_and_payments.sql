-- Rentals relaunch without online payment.
-- Staff check the driver license, insurance and paper rental agreement at the counter, and record
-- every payment, deposit and extra charge by hand. Money rows are append-only; mistakes are fixed
-- with a refund or a negative (discount) charge.

CREATE TABLE IF NOT EXISTS rental_counter_checks (
  reservation_id INTEGER PRIMARY KEY REFERENCES reservationsmvp (reservationid) ON DELETE RESTRICT,
  license_verified_at TIMESTAMPTZ,
  license_verified_by INTEGER REFERENCES admin_users (id) ON DELETE RESTRICT,
  insurance_verified_at TIMESTAMPTZ,
  insurance_verified_by INTEGER REFERENCES admin_users (id) ON DELETE RESTRICT,
  agreement_signed_at TIMESTAMPTZ,
  agreement_signed_by INTEGER REFERENCES admin_users (id) ON DELETE RESTRICT,
  note TEXT CHECK (note IS NULL OR length(note) <= 1000),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS rental_charges (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reservation_id INTEGER NOT NULL REFERENCES reservationsmvp (reservationid) ON DELETE RESTRICT,
  description TEXT NOT NULL CHECK (length(trim(description)) BETWEEN 1 AND 200),
  amount_cents INTEGER NOT NULL CHECK (amount_cents <> 0 AND abs(amount_cents) <= 10000000),
  created_by INTEGER REFERENCES admin_users (id) ON DELETE RESTRICT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_rental_charges_reservation ON rental_charges (reservation_id, created_at);

CREATE TABLE IF NOT EXISTS rental_payments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reservation_id INTEGER NOT NULL REFERENCES reservationsmvp (reservationid) ON DELETE RESTRICT,
  kind VARCHAR(20) NOT NULL CHECK (kind IN ('PAYMENT', 'REFUND', 'DEPOSIT', 'DEPOSIT_REFUND')),
  method VARCHAR(20) NOT NULL CHECK (method IN ('CASH', 'CARD', 'CLOVER', 'CHECK', 'OTHER')),
  amount_cents INTEGER NOT NULL CHECK (amount_cents > 0 AND amount_cents <= 10000000),
  reference TEXT CHECK (reference IS NULL OR length(reference) <= 120),
  note TEXT CHECK (note IS NULL OR length(note) <= 500),
  recorded_by INTEGER REFERENCES admin_users (id) ON DELETE RESTRICT,
  recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_rental_payments_reservation ON rental_payments (reservation_id, recorded_at);

CREATE OR REPLACE FUNCTION prevent_rental_money_mutation() RETURNS trigger AS $$
BEGIN
  RAISE EXCEPTION 'Rental payments and charges are append-only';
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS rental_payments_append_only ON rental_payments;
CREATE TRIGGER rental_payments_append_only BEFORE UPDATE OR DELETE ON rental_payments
  FOR EACH ROW EXECUTE FUNCTION prevent_rental_money_mutation();
DROP TRIGGER IF EXISTS rental_charges_append_only ON rental_charges;
CREATE TRIGGER rental_charges_append_only BEFORE UPDATE OR DELETE ON rental_charges
  FOR EACH ROW EXECUTE FUNCTION prevent_rental_money_mutation();
