-- Phase 7D: durable SMS delivery records and minimal employee account controls.
CREATE TABLE notification_outbox (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reservation_id INTEGER REFERENCES reservationsmvp (reservationid) ON DELETE RESTRICT,
  channel VARCHAR(12) NOT NULL CHECK (channel IN ('SMS')),
  event_type VARCHAR(80) NOT NULL CHECK (event_type ~ '^[A-Z][A-Z0-9_]{2,79}$'),
  business_event_key VARCHAR(180) NOT NULL,
  template_key VARCHAR(80) NOT NULL CHECK (template_key ~ '^[A-Z][A-Z0-9_]{2,79}$'),
  template_params JSONB NOT NULL DEFAULT '{}'::jsonb,
  content_hash CHAR(64) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'PROCESSING', 'RETRY_WAIT', 'SENT', 'DEAD_LETTER', 'SKIPPED')),
  attempt_count INTEGER NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
  next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  lease_token CHAR(36),
  lease_expires_at TIMESTAMPTZ,
  provider_message_id VARCHAR(160),
  provider_status VARCHAR(80),
  last_error_code VARCHAR(80),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  sent_at TIMESTAMPTZ,
  CONSTRAINT notification_outbox_business_event_unique UNIQUE (business_event_key),
  CONSTRAINT notification_outbox_reservation_event_unique UNIQUE (reservation_id, event_type, business_event_key),
  CONSTRAINT notification_outbox_lease_state_check CHECK (
    (status = 'PROCESSING' AND lease_token IS NOT NULL AND lease_expires_at IS NOT NULL) OR
    (status <> 'PROCESSING')
  )
);

CREATE INDEX idx_notification_outbox_eligible ON notification_outbox (next_attempt_at, id) WHERE status IN ('PENDING', 'RETRY_WAIT');
CREATE INDEX idx_notification_outbox_expired_lease ON notification_outbox (lease_expires_at, id) WHERE status = 'PROCESSING';
CREATE INDEX idx_notification_outbox_reservation ON notification_outbox (reservation_id, created_at DESC);
CREATE INDEX idx_notification_outbox_provider_message ON notification_outbox (provider_message_id) WHERE provider_message_id IS NOT NULL;

CREATE TABLE notification_attempts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  notification_id BIGINT NOT NULL REFERENCES notification_outbox (id) ON DELETE RESTRICT,
  attempt_number INTEGER NOT NULL CHECK (attempt_number > 0),
  result VARCHAR(20) NOT NULL CHECK (result IN ('SENT', 'RETRY_WAIT', 'DEAD_LETTER', 'SKIPPED')),
  safe_error_code VARCHAR(80),
  provider_message_id VARCHAR(160),
  duration_ms INTEGER CHECK (duration_ms >= 0),
  attempted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT notification_attempts_notification_attempt_unique UNIQUE (notification_id, attempt_number)
);

CREATE INDEX idx_notification_attempts_notification ON notification_attempts (notification_id, attempt_number DESC);

CREATE FUNCTION prevent_notification_attempt_mutation() RETURNS trigger AS $$
BEGIN
  RAISE EXCEPTION 'notification attempts are immutable';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER notification_attempts_immutable
  BEFORE UPDATE OR DELETE ON notification_attempts
  FOR EACH ROW EXECUTE FUNCTION prevent_notification_attempt_mutation();

