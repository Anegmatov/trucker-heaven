-- Tables retained for the original class-project API routes.

CREATE TABLE IF NOT EXISTS customers (
  custid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fname VARCHAR(80) NOT NULL,
  lname VARCHAR(80) NOT NULL,
  phonenumber VARCHAR(40) NOT NULL,
  email VARCHAR(160) NOT NULL,
  passwordhash TEXT NOT NULL,
  createdat TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_customers_email_lower ON customers (LOWER(email));

CREATE TABLE IF NOT EXISTS cars (
  carid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  make VARCHAR(80),
  model VARCHAR(80),
  year INTEGER CHECK (year BETWEEN 1886 AND 9999),
  status VARCHAR(30) NOT NULL DEFAULT 'Available',
  dailyrate NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (dailyrate >= 0),
  createdat TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS rental (
  rentid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rentdate TIMESTAMPTZ NOT NULL,
  returndate TIMESTAMPTZ NOT NULL,
  custid INTEGER NOT NULL REFERENCES customers (custid) ON DELETE RESTRICT,
  carid INTEGER NOT NULL REFERENCES cars (carid) ON DELETE RESTRICT,
  createdat TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (returndate > rentdate)
);

CREATE INDEX IF NOT EXISTS idx_rental_customer ON rental (custid);
CREATE INDEX IF NOT EXISTS idx_rental_car ON rental (carid);

CREATE TABLE IF NOT EXISTS paymentdetails (
  paymentid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rentid INTEGER REFERENCES rental (rentid) ON DELETE SET NULL,
  amount NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (amount >= 0),
  status VARCHAR(40),
  paymentreference VARCHAR(160) UNIQUE,
  paidat TIMESTAMPTZ,
  createdat TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE OR REPLACE VIEW rentaldetails AS
SELECT
  rental.rentid,
  rental.rentdate,
  rental.returndate,
  rental.custid,
  rental.carid,
  customers.fname,
  customers.lname,
  customers.email,
  cars.make,
  cars.model,
  cars.year,
  cars.status
FROM rental
JOIN customers ON customers.custid = rental.custid
JOIN cars ON cars.carid = rental.carid;
