-- Phase 9A repair: document revisions and customer-safe review instructions.
ALTER TABLE rental_documents ADD COLUMN IF NOT EXISTS customer_instruction VARCHAR(1000);
ALTER TABLE rental_documents ADD COLUMN IF NOT EXISTS superseded_at TIMESTAMPTZ;
ALTER TABLE rental_documents ADD COLUMN IF NOT EXISTS original_filename VARCHAR(255);
CREATE UNIQUE INDEX IF NOT EXISTS uq_rental_documents_current_type
  ON rental_documents (reservation_id, document_type) WHERE superseded_at IS NULL;

CREATE TABLE rental_document_review_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_id BIGINT NOT NULL REFERENCES rental_documents(id) ON DELETE RESTRICT,
  review_status VARCHAR(20) NOT NULL CHECK (review_status IN ('PENDING_REVIEW','APPROVED','REJECTED')),
  internal_note VARCHAR(1000), customer_instruction VARCHAR(1000),
  reviewed_by_admin_user_id INTEGER REFERENCES admin_users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_rental_document_review_history_document ON rental_document_review_history(document_id, created_at DESC);

CREATE FUNCTION prevent_rental_document_review_history_mutation() RETURNS trigger AS $$
BEGIN
  RAISE EXCEPTION 'rental document review history is immutable';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER rental_document_review_history_immutable
  BEFORE UPDATE OR DELETE ON rental_document_review_history
  FOR EACH ROW EXECUTE FUNCTION prevent_rental_document_review_history_mutation();

CREATE FUNCTION protect_rental_document_revision() RETURNS trigger AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'rental document revisions cannot be deleted';
  END IF;

  IF NEW.reservation_id IS DISTINCT FROM OLD.reservation_id
     OR NEW.document_type IS DISTINCT FROM OLD.document_type
     OR NEW.storage_name IS DISTINCT FROM OLD.storage_name
     OR NEW.mime_type IS DISTINCT FROM OLD.mime_type
     OR NEW.byte_size IS DISTINCT FROM OLD.byte_size
     OR NEW.original_filename IS DISTINCT FROM OLD.original_filename
     OR NEW.uploaded_at IS DISTINCT FROM OLD.uploaded_at THEN
    RAISE EXCEPTION 'rental document revision evidence is immutable';
  END IF;

  IF OLD.superseded_at IS NOT NULL AND NEW.superseded_at IS DISTINCT FROM OLD.superseded_at THEN
    RAISE EXCEPTION 'superseded rental document revisions are immutable';
  END IF;

  IF OLD.review_status IN ('APPROVED', 'REJECTED') AND (
       NEW.review_status IS DISTINCT FROM OLD.review_status
       OR NEW.review_note IS DISTINCT FROM OLD.review_note
       OR NEW.customer_instruction IS DISTINCT FROM OLD.customer_instruction
       OR NEW.reviewed_by_admin_user_id IS DISTINCT FROM OLD.reviewed_by_admin_user_id
       OR NEW.reviewed_at IS DISTINCT FROM OLD.reviewed_at
     ) THEN
    RAISE EXCEPTION 'finalized rental document reviews are immutable';
  END IF;

  IF OLD.review_status = 'PENDING_REVIEW' AND NEW.review_status = 'PENDING_REVIEW' AND (
       NEW.review_note IS DISTINCT FROM OLD.review_note
       OR NEW.customer_instruction IS DISTINCT FROM OLD.customer_instruction
       OR NEW.reviewed_by_admin_user_id IS DISTINCT FROM OLD.reviewed_by_admin_user_id
       OR NEW.reviewed_at IS DISTINCT FROM OLD.reviewed_at
     ) THEN
    RAISE EXCEPTION 'pending rental document review metadata cannot be altered';
  END IF;

  IF OLD.review_status = 'PENDING_REVIEW'
     AND NEW.review_status NOT IN ('PENDING_REVIEW', 'APPROVED', 'REJECTED') THEN
    RAISE EXCEPTION 'invalid rental document review transition';
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER rental_document_revision_protected
  BEFORE UPDATE OR DELETE ON rental_documents
  FOR EACH ROW EXECUTE FUNCTION protect_rental_document_revision();
